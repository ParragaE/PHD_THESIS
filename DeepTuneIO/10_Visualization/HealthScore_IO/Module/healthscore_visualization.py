#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
DeepTuneIO Analyzer — Module 07.3: HealthScore_IO Visualization

Consumes the ranked CSV generated by Module 07.2.
It does not recompute HealthScore_IO.
"""

from pathlib import Path
import argparse
import pandas as pd
import matplotlib.pyplot as plt


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--input-csv", type=Path, required=True)
    p.add_argument("--output-dir", type=Path, required=True)
    p.add_argument("--stem", required=True)
    args = p.parse_args(argv)

    df = pd.read_csv(args.input_csv)
    required = ["Processes_IO", "HealthScore_IO"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    args.output_dir.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(7.2, 4.6))

    if "Access_Mode" in df.columns:
        for mode, part in df.groupby("Access_Mode", dropna=False):
            part = part.sort_values("Processes_IO")
            ax.plot(
                part["Processes_IO"],
                part["HealthScore_IO"],
                marker="o",
                label=f"Access mode {mode}",
            )
        ax.legend()
    else:
        part = df.sort_values("Processes_IO")
        ax.plot(part["Processes_IO"], part["HealthScore_IO"], marker="o")

    ax.set_xlabel("I/O processes")
    ax.set_ylabel(r"HealthScore$_{IO}$")
    ax.set_ylim(0, 10)
    ax.grid(True, alpha=0.25)
    fig.tight_layout()

    png = args.output_dir / f"07_3_healthscore_io_{args.stem}.png"
    pdf = args.output_dir / f"07_3_healthscore_io_{args.stem}.pdf"
    fig.savefig(png, dpi=300, bbox_inches="tight")
    fig.savefig(pdf, bbox_inches="tight")
    plt.close(fig)

    print(f"PNG: {png}")
    print(f"PDF: {pdf}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
