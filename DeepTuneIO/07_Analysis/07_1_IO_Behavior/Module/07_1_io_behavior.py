    aliases = {
        "JobID": "Jobid",
        "jobid": "Jobid",
        "Job_ID": "Jobid",
        "Process IO": "Process_IO",
        "Processes IO": "Process_IO",
        "Processes_IO": "Process_IO",
        "Processes": "Process_IO",
        "Nprocs": "Process_IO",
        "Nnodes": "Nodes",
        "NNodes": "Nodes",
        "Node_Count": "Nodes",
        "Node Count": "Nodes",
        "Nodes_IO": "Nodes",
        "Access Mode": "Access_Mode",
        "AccessMode": "Access_Mode",
        "POSIX_BYTES_READS": "POSIX_BYTES_READ",
        "POSIX_SEQ_READ": "POSIX_SEQ_READS",
        "POSIX_CONSEC_READ": "POSIX_CONSEC_READS",
    }

    for old, new in aliases.items():
        if old in df.columns and new not in df.columns:
            df = df.rename(columns={old: new})

    return df


