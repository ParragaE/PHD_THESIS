def relative_error(reference: float | None, candidate: float | None) -> float | None:
    if reference in (None, 0) or candidate is None:
        return None
    return abs(float(candidate) - float(reference)) / abs(float(reference))


def filesystem_dataset_size(dataset_path: Path | None) -> int | None:
    """Return dataset size from an accessible file or directory."""
    if dataset_path is None or not dataset_path.exists():
        return None
    if dataset_path.is_file():
        return int(dataset_path.stat().st_size)
    if dataset_path.is_dir():
        return int(sum(p.stat().st_size for p in dataset_path.rglob("*") if p.is_file()))
    return None


def resolve_dataset_size(
    manual_size_bytes: float,
    filesystem_size_bytes: float | None = None,
    darshan_size_bytes: float | None = None,
    tolerance: float = 0.01,
) -> dict:
    """Validate automatic dataset-size evidence against the manual reference."""
    manual = int(manual_size_bytes)
    fs = int(filesystem_size_bytes) if filesystem_size_bytes is not None else None
    darshan = int(darshan_size_bytes) if darshan_size_bytes is not None else None

    fs_error = relative_error(manual, fs)
    darshan_error = relative_error(manual, darshan)
    fs_ok = fs_error is not None and fs_error <= tolerance
    darshan_ok = darshan_error is not None and darshan_error <= tolerance

    if fs_ok:
        selected, source, validated = fs, "filesystem_validated", True
    elif darshan_ok:
        selected, source, validated = darshan, "darshan_validated", True
    elif fs is None and darshan is None:
        selected, source, validated = manual, "manual_fallback_unavailable", False
    else:
        selected, source, validated = manual, "manual_fallback_mismatch", False

    return {
        "Dataset_Size_Manual_Bytes": manual,
        "Dataset_Size_Filesystem_Bytes": fs,
        "Dataset_Size_Darshan_Bytes": darshan,
        "Dataset_Size_Bytes": selected,
        "Dataset_Size_Source": source,
        "Dataset_Size_Validated": validated,
        "Dataset_Size_Filesystem_Relative_Error": fs_error,
        "Dataset_Size_Darshan_Relative_Error": darshan_error,
    }


def infer_darshan_dataset_size(df: pd.DataFrame) -> int | None:
    """Infer a dataset-size validation candidate from Darshan Parser data.

    Uses POSIX_MAX_BYTE_READ + 1, never POSIX_BYTES_READ. File candidates are
    deduplicated within each Jobid and summed; the median total across jobs is
    returned. The result is only a validation candidate against the manual
    reference.
    """
    if "POSIX_MAX_BYTE_READ" not in df.columns:
        return None

    work = df.copy()
    work["POSIX_MAX_BYTE_READ"] = pd.to_numeric(work["POSIX_MAX_BYTE_READ"], errors="coerce")
    work = work[work["POSIX_MAX_BYTE_READ"].notna() & (work["POSIX_MAX_BYTE_READ"] >= 0)]
    if work.empty:
        return None

    file_key = next((c for c in ("Dataset_Path", "File Name", "File_Name", "Filename") if c in work.columns), None)

    per_job = []
    if "Jobid" in work.columns:
        for _, job_df in work.groupby("Jobid", dropna=False):
            if file_key is not None:
                per_file = job_df.groupby(file_key, dropna=False)["POSIX_MAX_BYTE_READ"].max().dropna()
                if len(per_file):
                    per_job.append(float((per_file + 1).sum()))
            else:
                value = job_df["POSIX_MAX_BYTE_READ"].max()
                if pd.notna(value):
                    per_job.append(float(value + 1))

    if per_job:
        return int(round(float(np.median(per_job))))

    value = work["POSIX_MAX_BYTE_READ"].max()
    return int(value + 1) if pd.notna(value) else None


def infer_separator(path: Path) -> str:
    """Infer separator from the first line."""
    first_line = path.read_text(encoding="utf-8", errors="replace").splitlines()[0]
    if ";" in first_line and first_line.count(";") >= first_line.count(","):
        return ";"
    return ","


def normalize_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Normalize column names and provide common aliases."""
